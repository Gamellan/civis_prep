QuestionModel _question({
  required String id,
  required String task,
  required String topic,
  required String prompt,
  required String optionA,
  required String optionB,
  required String optionC,
  required String optionD,
  required String correctOptionId,
  required String explanation,
  required String difficulty,
}) {
  return QuestionModel(
    id: id,
    exam: 'CCSE',
    task: task,
    topic: topic,
    prompt: prompt,
    options: [
      QuestionOption(id: 'a', text: optionA, isCorrect: correctOptionId == 'a'),
      QuestionOption(id: 'b', text: optionB, isCorrect: correctOptionId == 'b'),
      QuestionOption(id: 'c', text: optionC, isCorrect: correctOptionId == 'c'),
      QuestionOption(id: 'd', text: optionD, isCorrect: correctOptionId == 'd'),
    ],
    correctOptionId: correctOptionId,
    explanation: _normalizeCcseExplanation(explanation),
    difficulty: difficulty,
    sourceReference: 'Instituto Cervantes + elaboración propia',
    contentVersion: 'v2',
  );
}

String _normalizeCcseExplanation(String explanation) {
  final normalized = explanation.trim().replaceAll(RegExp(r'\s+'), ' ');
  if (normalized.endsWith('.')) {
    return normalized;
  }

  return '$normalized.';
}
